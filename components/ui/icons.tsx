/* ---------------------------------------------------------------------------
 * Icons below share one base. ALWAYS use an SVG icon for UI chrome —
 * never a Unicode symbol (▶ ✓ ★ 📅 …): iOS renders many of those as
 * colored emoji, which is exactly the "sidebar icons look broken on iPhone"
 * bug. Emoji are only for user content (reactions, the emoji picker).
 * ------------------------------------------------------------------------- */

type IconProps = { className?: string; strokeWidth?: number };

function Svg({
  className,
  strokeWidth = 1.75,
  fill = "none",
  children,
}: IconProps & { fill?: string; children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill={fill}
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      className={className}
    >
      {children}
    </svg>
  );
}

